"""Import the 15 laboratory question sheets from DOCX into the website."""
from html import escape
from html.parser import HTMLParser
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET
import zipfile

ROOT = Path(__file__).resolve().parents[1]
NS = {"w": "http://schemas.openxmlformats.org/wordprocessingml/2006/main"}
W = "{" + NS["w"] + "}"


class PlainText(HTMLParser):
    def __init__(self):
        super().__init__()
        self.parts = []

    def handle_data(self, data):
        self.parts.append(data)


def inline(paragraph):
    parts = []
    for run in paragraph.findall(".//w:r", NS):
        text = "".join(
            escape(node.text or "") if node.tag == W + "t"
            else "<br>" if node.tag in (W + "br", W + "cr")
            else " " if node.tag == W + "tab" else ""
            for node in run
        )
        for name, tag in [("b", "strong"), ("i", "em")]:
            setting = run.find(f"w:rPr/w:{name}", NS)
            if setting is not None and setting.get(W + "val", "1") not in ("0", "false", "off"):
                text = f"<{tag}>{text}</{tag}>"
        parts.append(text)
    return "".join(parts)


def import_lab(number):
    source = ROOT / "задание" / f"{number}-лаб.docx"
    with zipfile.ZipFile(source) as archive:
        document = ET.fromstring(archive.read("word/document.xml"))
    for tag in ("tbl", "drawing", "pict", "object"):
        assert not document.findall(f".//w:{tag}", NS), f"Unsupported content ({tag}): {source}"
    paragraphs = [
        p for p in document.findall("w:body/w:p", NS)
        if "".join(t.text or "" for t in p.findall(".//w:t", NS)).strip()
    ]
    title = "".join(t.text or "" for t in paragraphs[0].findall(".//w:t", NS)).strip()
    assert title.startswith(f"{number}-"), f"Wrong topic number: {source}"
    questions = []
    for paragraph in paragraphs[1:]:
        if paragraph.find("w:pPr/w:numPr", NS) is not None:
            questions.append([])
        assert questions, f"Unexpected unnumbered question: {source}"
        # A paragraph without numbering continues the preceding question.
        questions[-1].append(f"<p>{inline(paragraph)}</p>")
    assert len(questions) == 10, f"Expected ten questions: {source}"
    markup = f"<h3>{inline(paragraphs[0])}</h3><ol>" + "".join(
        "<li>" + "".join(parts) + "</li>" for parts in questions
    ) + "</ol>"
    parsed = PlainText()
    parsed.feed(markup)
    original = "".join(t.text or "" for t in document.findall("w:body//w:t", NS))
    normalize = lambda text: re.sub(r"\s+", "", text)
    assert normalize("".join(parsed.parts)) == normalize(original), f"Text lost: {source}"
    return {"title": title, "filePath": source.relative_to(ROOT).as_posix(), "html": markup}


if __name__ == "__main__":
    labs = {number: import_lab(number) for number in range(1, 16)}
    output = ROOT / "assets" / "lab-texts.js"
    output.parent.mkdir(exist_ok=True)
    output.write_text(
        "// Generated by scripts/import_labs.py from задание/*-лаб.docx.\nwindow.labTexts = "
        + json.dumps(labs, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print("Imported 15 labs, 150 questions. Verified complete source text preservation.")
